COMMON = {"Valentine's Day", "Mother's Day", "Father's Day", 'Halloween',
          'Thanksgiving Day', 'Christmas Eve', 'Christmas Day'}


def translate(name, country):
    observed = name.endswith(' (observed)')
    base = name.removesuffix(' (observed)')
    if country == 'US' and base == 'Labor Day':
        result = '美国劳动节'
    elif country == 'FR' and base == 'May Day':
        result = '劳动节'
    else:
        result = TRANSLATIONS[base]  # Fail on new/untranslated upstream names.
    return result + ('（补假）' if observed else '')


def generate():
    if holidays.__version__ != VERSION:
        raise SystemExit(f'Expected holidays=={VERSION}, got {holidays.__version__}')
    datasets = {}
    for profile, (country, subdivision) in PROFILES.items():
        calendar = holidays.country_holidays(country, subdiv=subdivision, years=YEARS,
                                            language='en_US', observed=True)
        # Keep each coincident holiday separately instead of copying the joined upstream label.
        datasets[profile] = sorted({(date, translate(name, country))
                                   for date, joined in calendar.items() if date.year in YEARS
                                   for name in joined.split('; ')})
    us = holidays.US(years=YEARS, categories=('public', 'unofficial'),
                     language='en_US', observed=False)
    datasets['common'] = sorted({(date, translate(name, 'US'))
                                 for date, joined in us.items() if date.year in YEARS
                                 for name in joined.split('; ') if name in COMMON})
    names = sorted({name for rows in datasets.values() for _, name in rows})
    indexes = {name: index for index, name in enumerate(names)}

    def rows(profile):
        grouped = {}
        for date, name in datasets[profile]:
            grouped.setdefault(date.year, []).append(f'{date:%m%d}:{indexes[name]}')
        return '\n'.join(f'{year}|' + ','.join(items) for year, items in sorted(grouped.items()))

    output = ['// Generated by scripts/generate-festivals.py; do not edit by hand.',
              f'// python-holidays {VERSION}, MIT. See Data/holidays-LICENSE.txt and Data/FESTIVALS.md.',
              '// Coverage: 1901–2099; historical start years follow upstream; future dates are projections.',
              'enum GeneratedFestivalData {', f'    static let sourceVersion = "{VERSION}"', '    static let names: [String] = [']
    output += [f'        {json.dumps(name, ensure_ascii=False)},' for name in names]
    output += ['    ]', '    static let common = """', rows('common'), '"""',
               '    static let countries: [FestivalCalendar: String] = [']
    for profile in PROFILES:
        output += [f'        .{profile}: """', rows(profile), '""",']
    output += ['    ]', '}', '']
    return '\n'.join(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Festival snapshot differs; regenerate and review it.')
        print('Festival snapshot matches pinned upstream data.')
    else:
        TARGET.write_text(content)
        print(f'Generated {TARGET.name} ({len(content.encode())} bytes)')
